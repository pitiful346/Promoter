/// Class representing a realistic event for development, testing,
/// and Mapbox clustering visualization in the Porto area.
class DevelopmentEvent {
  final String id;
  final String title;
  final String category; // 'Música', 'Social', 'Arte', 'Drop'
  final DateTime dateTime;
  final DateTime? endDate;
  final String locationName; // Venue name (e.g., 'Plano B', 'Hard Club', 'Jardim do Morro')
  final String locationAddress;
  final double latitude;
  final double longitude;
  final String distance; // e.g., '450 m', '1.2 km'
  final double distanceKm;
  final String image; // Unsplash high-res nightlife/concert/party/art photo
  final double priceMin;
  final bool isFree;
  final String ticketStatus; // 'AVAILABLE', 'SOON', 'SOLD_OUT'
  final String ticketUrl;
  final String description;
  final int clickCount;
  final bool isBoosted;

  const DevelopmentEvent({
    required this.id,
    required this.title,
    required this.category,
    required this.dateTime,
    this.endDate,
    required this.locationName,
    required this.locationAddress,
    required this.latitude,
    required this.longitude,
    required this.distance,
    required this.distanceKm,
    required this.image,
    required this.priceMin,
    required this.isFree,
    required this.ticketStatus,
    this.ticketUrl = 'https://shotgun.live/pt',
    required this.description,
    this.clickCount = 150,
    this.isBoosted = false,
  });

  /// Mapbox / FlutterFlow LatLng coordinates.
  LatLng get coordinates => LatLng(latitude, longitude);

  /// Converts this DevelopmentEvent into a Map formatted for Firestore's 'events' collection.
  Map<String, dynamic> toFirestoreMap({DocumentReference? organizerRef}) {
    return {
      'name': title,
      'description': description,
      'location': locationAddress,
      'venue_name': locationName,
      'coordenadas': coordinates,
      'image': image,
      'start_date': dateTime,
      'end_date': endDate ?? dateTime.add(const Duration(hours: 4)),
      'price_min': priceMin,
      'is_free': isFree,
      'ticket_status': ticketStatus,
      'ticket_url': ticketUrl,
      'categoria': [category],
      'click_count': clickCount,
      'is_boosted': isBoosted,
      'is_archived': false,
      if (organizerRef != null) 'organizer_id': organizerRef,
    };
  }

  /// Converts this DevelopmentEvent into an in-memory [EventsRecord] for Flutter UI testing.
  EventsRecord toEventsRecord([DocumentReference? ref]) {
    final docRef = ref ?? _resolveDefaultReference(id);
    return EventsRecord.getDocumentFromData(
      toFirestoreMap(),
      docRef,
    );
  }

  static DocumentReference _resolveDefaultReference(String id) {
    try {
      if (Firebase.apps.isNotEmpty) {
        return FirebaseFirestore.instance.collection('events').doc(id);
      }
    } catch (_) {
      // Fallback for headless unit test runners without Firebase platform channels
    }
    return _MockDocumentReference(id);
  }

  /// JSON serialization helper
  Map<String, dynamic> toJson() => {
        'id': id,
        'title': title,
        'category': category,
        'dateTime': dateTime.toIso8601String(),
        'endDate': endDate?.toIso8601String(),
        'locationName': locationName,
        'locationAddress': locationAddress,
        'latitude': latitude,
        'longitude': longitude,
        'distance': distance,
        'distanceKm': distanceKm,
        'image': image,
        'priceMin': priceMin,
        'isFree': isFree,
        'ticketStatus': ticketStatus,
        'ticketUrl': ticketUrl,
        'description': description,
        'clickCount': clickCount,
        'isBoosted': isBoosted,
      };
}

