/// Helper that converts all 20 Porto mock events directly into [EventsRecord] objects,
/// allowing FlutterFlow / Flutter stream builders and event cards to render them immediately.
List<EventsRecord> generateMockEventsRecords() {
  return generateMockEvents().map((e) => e.toEventsRecord()).toList();
}

/// Convenience function to seed all 20 mock events into real Firebase Firestore collection 'events'.
/// Can be invoked in debug/admin tools to populate the database in seconds.
Future<List<String>> seedEventsToFirestore({
  bool clearExisting = false,
  DocumentReference? organizerRef,
}) async {
  final firestore = FirebaseFirestore.instance;
  final collection = firestore.collection('events');
  final events = generateMockEvents();
  final writtenIds = <String>[];

  for (final event in events) {
    final docRef = collection.doc(event.id);
    await docRef.set(
      event.toFirestoreMap(organizerRef: organizerRef),
      SetOptions(merge: true),
    );
    writtenIds.add(event.id);
  }

  return writtenIds;
}

